@router.get("/comparison")
async def get_comparison():
    """Side-by-side of what each model is for, and why the pipeline uses both."""
    measured = _measured()
    yolo_val = _yolo_validation()
    return success_response("Model comparison", {
        "rows": benchmark_service.comparison_table(
            resnet_test_acc=measured["test_acc"] if measured else None,
            yolo_map50=yolo_val.get("mAP50"),
            yolo_val_images=yolo_val.get("val_images"),
        ),
        "note": (
            "The classifier's accuracy is measured on the full GTSRB test set and does not "
            "change between machines. The detector's mAP comes from held-out scenes whose "
            "backgrounds are generated, so read it as a score on that distribution rather "
            "than on real street photography. Latency is measured live — call /model/benchmark."
        ),
    })


@router.get("/benchmark")
async def run_benchmark(runs: int = Query(8, ge=1, le=50)):
    """
    Measure YOLOv8 and ResNet50 inference latency on this machine, right now.

    First call is slower — the weights load on demand.
    """
    try:
        return success_response("Benchmark complete", benchmark_service.run_benchmark(runs))
    except Exception as e:
        return error_response(str(e), "BENCHMARK_ERROR", 500)

