"""
What the two models actually are, and how well they actually do.

Everything on this page is either read from a training log, read from the weights
file itself, or measured. Nothing is typed in by hand, and every figure carries the
size of the set behind it, because an examiner asking "how did you get that?"
deserves an answer that matches the logs on disk.

Both measurements are files on disk, regenerated by their own scripts:

    backend>  .venv\\Scripts\\python.exe -m app.scripts.measure_resnet
    ai/yolov8_module>  python train_synthetic.py --val-only

Re-run the matching one after any retrain. If a file is absent the page says that
model has not been measured yet instead of inventing a figure — and the detector
falls back to reporting its original two-image run, labelled as such.
"""

