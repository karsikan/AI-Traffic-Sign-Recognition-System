"""
Driver report as a PDF.

Pulls together everything the app knows about one driver — outstanding fines and what
they cost today, the demerit balance, documents and their expiry, and recent AI
detections — into a single document they can print or send on.

Built with ReportLab's platypus flowables so the layout reflows across pages by itself
rather than being positioned by hand.
"""

